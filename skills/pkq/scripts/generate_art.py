#!/usr/bin/env python3
"""
Generate Pikachu (or any Pokemon) ASCII art for Free Code CLI.
Uses img2unicode with FastQuadDualOptimizer for quad-block Unicode art.

Usage:
    python3 generate_art.py                          # Default: Pikachu, 20x40
    python3 generate_art.py --pokemon 25             # By Pokedex ID
    python3 generate_art.py --image /path/to/img.png # Custom image
    python3 generate_art.py --height 10 --width 20   # Custom size
    python3 generate_art.py --output /tmp/art.txt    # Save to file
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

FREECODE_DIR = os.path.expanduser("~/projects/free-code")
CLAWD_TSX = os.path.join(FREECODE_DIR, "src/components/LogoV2/Clawd.tsx")


def ensure_img2unicode():
    """Install img2unicode in a temp venv if not available."""
    venv = "/tmp/img2u-env"
    pip = os.path.join(venv, "bin", "pip")
    python = os.path.join(venv, "bin", "python3")

    if not os.path.exists(python):
        print("[1/4] Creating venv...")
        subprocess.run([sys.executable, "-m", "venv", venv], check=True)
        print("[2/4] Installing img2unicode...")
        subprocess.run([pip, "install", "img2unicode"], check=True,
                      capture_output=True)

    try:
        subprocess.run([python, "-c", "import img2unicode"], check=True,
                      capture_output=True)
    except subprocess.CalledProcessError:
        print("[2/4] Installing img2unicode...")
        subprocess.run([pip, "install", "img2unicode"], check=True,
                      capture_output=True)

    return python


def download_sprite(pokemon_id: int) -> str:
    """Download official Pokemon sprite from PokeAPI."""
    import urllib.request
    url = f"https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/other/official-artwork/{pokemon_id}.png"
    path = os.path.join(tempfile.gettempdir(), f"pokemon_{pokemon_id}.png")
    print(f"[3/4] Downloading sprite #{pokemon_id}...")
    urllib.request.urlretrieve(url, path)
    return path


def generate_art(python: str, image_path: str, height: int, width: int,
                 output_path: str | None = None) -> list[str]:
    """Generate Unicode block art from image."""
    out = output_path or os.path.join(tempfile.gettempdir(), "pokemon_art.txt")

    script = f"""
from PIL import Image
import img2unicode

img = Image.open('{image_path}').convert('RGBA')
bg = Image.new('RGBA', img.size, (0, 0, 0, 255))
bg.paste(img, mask=img.split()[3])
bg.save('/tmp/_pokemon_nobg.png')

optimizer = img2unicode.FastQuadDualOptimizer()
renderer = img2unicode.Renderer(default_optimizer=optimizer, max_h={height}, max_w={width})
renderer.render_terminal('/tmp/_pokemon_nobg.png', '{out}')
"""
    print(f"[3/4] Generating {height}x{width} art...")
    subprocess.run([python, "-c", script], check=True)

    with open(out, 'r') as f:
        lines = [line.rstrip().replace('\u202d', '') for line in f.readlines()]

    return lines


def patch_clawd(lines: list[str]):
    """Patch Clawd.tsx with new art."""
    # Build the ANSI lines as JS string literals
    js_lines = []
    for line in lines:
        escaped = line.replace("\\", "\\\\").replace('"', '\\"')
        # Convert raw ESC to \x1b
        escaped = escaped.replace("\x1b", "\\x1b")
        js_lines.append(f'  "{escaped}"')

    art_array = ",\n".join(js_lines)

    component = f'''import * as React from 'react';
import {{ Box, Text }} from '../../ink.js';
import {{ env }} from '../../utils/env.js';
export type ClawdPose = 'default' | 'arms-up'
| 'look-left'
| 'look-right';

type Props = {{
  pose?: ClawdPose;
}};

// Auto-generated by /pkq skill using img2unicode
const PIKACHU_LINES = [
{art_array},
];

export function Clawd({{ pose = 'default' }}: Props) {{
  if (env.terminal === "Apple_Terminal") {{
    return <AppleTerminalClawd />;
  }}

  return (
    <Box flexDirection="column">
      {{PIKACHU_LINES.map((line, i) => (
        <Text key={{i}}>{{line}}</Text>
      ))}}
    </Box>
  );
}}

function AppleTerminalClawd() {{
  return (
    <Box flexDirection="column" alignItems="center">
      <Text color="clawd_body">Pikachu</Text>
    </Box>
  );
}}
'''

    with open(CLAWD_TSX, 'w') as f:
        f.write(component)
    print(f"[4/4] Patched {CLAWD_TSX}")


def build_freecode():
    """Rebuild Free Code CLI."""
    print("[BUILD] Compiling cli-dev...")
    result = subprocess.run(
        ["bun", "run", "build:dev"],
        cwd=FREECODE_DIR,
        capture_output=True, text=True
    )
    if result.returncode == 0:
        print("[DONE] Built ./cli-dev successfully!")
    else:
        print(f"[ERROR] Build failed:\n{result.stderr}")
        sys.exit(1)


def main():
    parser = argparse.ArgumentParser(description="Pokemon ASCII art for Free Code CLI")
    parser.add_argument("--pokemon", "-p", type=int, default=25,
                       help="Pokedex ID (default: 25 = Pikachu)")
    parser.add_argument("--image", "-i", type=str, default=None,
                       help="Custom image path (overrides --pokemon)")
    parser.add_argument("--height", type=int, default=20,
                       help="Art height in rows (default: 20)")
    parser.add_argument("--width", type=int, default=40,
                       help="Art width in columns (default: 40)")
    parser.add_argument("--output", "-o", type=str, default=None,
                       help="Save art to file (without patching)")
    parser.add_argument("--no-build", action="store_true",
                       help="Skip rebuild after patching")
    parser.add_argument("--preview", action="store_true",
                       help="Preview art in terminal without patching")

    args = parser.parse_args()

    # Step 1: Ensure img2unicode
    python = ensure_img2unicode()

    # Step 2: Get image
    if args.image:
        image_path = args.image
    else:
        image_path = download_sprite(args.pokemon)

    # Step 3: Generate art
    lines = generate_art(python, image_path, args.height, args.width, args.output)

    if args.preview:
        print("\n--- Preview ---")
        for line in lines:
            print(line)
        print("--- End ---")
        return

    if args.output:
        print(f"[DONE] Art saved to {args.output}")
        return

    # Step 4: Patch and build
    patch_clawd(lines)

    if not args.no_build:
        build_freecode()


if __name__ == "__main__":
    main()
